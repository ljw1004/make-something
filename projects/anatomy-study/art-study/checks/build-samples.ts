/** Build consecutive illustrated excerpts; keep full manuscripts as source editions. */
import {readFileSync, writeFileSync, readdirSync} from 'node:fs';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
import {parseStory} from '../../../../src/story/parser.ts';
import {itemPresentation} from '../../../../src/engine/presentation.ts';

const root=resolve(import.meta.dirname,'..');
const selected=[1,4,8,18];
const omittedCellParts=['opening-mitochondria','school-sugar-carrier','school-ribosome'];
const withoutSources=(value:unknown)=>JSON.parse(JSON.stringify(value,(key,value)=>key==='source'?undefined:value));
const themes=process.argv.slice(2);
if(!themes.length)themes.push(...readdirSync(root).filter(p=>{
  try{return readFileSync(resolve(root,p,'comparison-assets.json'),'utf8').length>0;}catch{return false;}
}));
for(const theme of themes){
  const dir=resolve(root,theme),source=readFileSync(resolve(dir,'anatomy.md'),'utf8');
  const full=parseStory(source),sections=source.split(/(?=^## )/m);
  const heading=sections[0].split('\n')[0]+' — Four-chapter art sample';
  const chapters=selected.map(n=>sections[n].trim());
  // Later cell fittings and its later name are outside this excerpt.
  chapters[0]=chapters[0].replace(/^  - from chapter `cell-energy`:.*\n/gm,'');
  for(const id of omittedCellParts){
    chapters[0]=chapters[0].replace(new RegExp('^  - unnamed slot: accepts `'+id+'`[^\\n]*\\n','gm'),'');
    chapters[0]=chapters[0].replace(new RegExp('^- `opening-cell`\\n  \\[`'+id+'`\\][\\s\\S]*?(?=^- |^\\*\\*|^> NOTE:|$(?![\\s\\S]))','gm'),'');
  }
  chapters[0]=chapters[0].replace(/([^\n])\n\*\*Combinations\*\*/, '$1\n\n**Combinations**');
  // The full book creates muscle cells in chapter 3; this excerpt supplies them.
  const muscle=itemPresentation(full,3,'id:prelude-myoblasts');
  assert(muscle.icon,`${theme}: missing muscle cells`);
  const rawMuscle=/^- `prelude-myoblasts` Muscle cells\n([\s\S]*?)(?=^- |^\*\*|^## )/m.exec(source);
  assert(rawMuscle,`${theme}: missing muscle declaration`);
  const originalIcon=rawMuscle[1].split('\n').find(l=>/^  - icon:/.test(l));
  assert(originalIcon);
  const icon=originalIcon.replace(/!\[[^\]]*\]\([^)]*\)/,`![Muscle cells](${muscle.icon.url})`);
  chapters[1]=chapters[1].replace(/^- `prelude-myoblasts`\s*$/m,
    '- `prelude-myoblasts` Muscle cells\n'+icon+'\n  {Separate elongated muscle cells contain parallel protein fibres. This supply includes enough cells for both arm regions.}\n');
  chapters[1]=chapters[1].replace("Return to the arm's anatomical model.","Explore the arm's anatomical model.");
  const background=chapters[3].split('\n').find(l=>l.startsWith('background:'));
  assert(background);
  const output=heading+'\n\nExplore four illustrated chapters: a cell boundary, bones and muscles, hearing, and digestion. They play consecutively in this sample.\n\n'+
    '> NOTE: Generated by checks/build-samples.ts from this theme’s full anatomy.md. Original chapter numbers: 1, 4, 8, 18. See the shared Anatomy design brief.\n\n'+
    chapters.join('\n\n')+'\n\n## `art-sample-finish` Four chapters complete\n'+background+'\n\nYou have built a cell boundary, fitted bone and muscle, connected an ear, and broken down a meal. This is the end of the four-chapter artwork sample.\n';
  const sample=parseStory(output);
  assert.equal(sample.chapters.length,5);
  for(let i=0;i<4;i++){
    assert.deepEqual(withoutSources(sample.chapters[i].goals),withoutSources(full.chapters[selected[i]-1].goals));
    assert.equal(sample.chapters[i].image,full.chapters[selected[i]-1].image);
  }
  assert.equal(Object.keys(sample.items).length,33);
  for(const [id,item] of Object.entries(sample.items)){
    const n=selected.findIndex(number=>full.chapters[number-1].items.includes(id));
    const i=n<0?1:n;
    assert.deepEqual(withoutSources(itemPresentation(sample,i,id).icon),withoutSources(itemPresentation(full,selected[i]-1,id).icon),`${theme}: ${id} icon changed`);
    assert(item.icon,`${theme}: ${id} has no icon`);
    assert(!/placeholder|unillustrated|neutral/.test(item.icon.url),`${theme}: ${id} placeholder`);
    for(const slot of item.slots){
      assert(full.items[id].slots.some(other=>JSON.stringify(withoutSources(slot))===JSON.stringify(withoutSources(other))),`${theme}: ${id} fitting changed`);
    }
  }
  const recipeKey=(r:typeof sample.recipes[number])=>JSON.stringify(withoutSources({a:r.a,b:r.b,at:r.at,hotspot:r.hotspot,result:r.result,installation:r.installation}));
  const originalRecipes=new Set(full.recipes.map(recipeKey));
  for(const recipe of sample.recipes)assert(originalRecipes.has(recipeKey(recipe)),`${theme}: recipe changed`);
  writeFileSync(resolve(dir,'sample.md'),output);
  console.log(`${theme}: four consecutive illustrated chapters + ending, 33 items`);
}
